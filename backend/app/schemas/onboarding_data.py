def get_questions_for_interest(interest_id: str | None = None) -> list[dict]:
    """
    Return assessment questions for the selected field of interest.

    The database currently stores UUIDs for fields of interest.
    The question bank can therefore be extended later by mapping
    actual interest UUIDs to one of the question sets above.

    For now, if no exact interest mapping exists, use the default
    question set rather than returning an empty assessment.
    """

    if interest_id and interest_id in ASSESSMENT_QUESTIONS:
        return ASSESSMENT_QUESTIONS[interest_id]

    return ASSESSMENT_QUESTIONS["default"]


CONFIDENCE_WEIGHTS = {
    "self_report": 0.40,
    "assessment": 0.40,
    "evidence": 0.20
}


def calculate_confidence(
    self_report_score: float,
    assessment_score: float,
    evidence_score: float
) -> float:
    score = (
        (self_report_score * CONFIDENCE_WEIGHTS["self_report"]) +
        (assessment_score * CONFIDENCE_WEIGHTS["assessment"]) +
        (evidence_score * CONFIDENCE_WEIGHTS["evidence"])
    )

    return max(0.0, min(100.0, score))


def get_self_report_score(level: str) -> float:
    mapping = {
        "beginner": 30.0,
        "intermediate": 45.0,
        "advanced": 60.0
    }

    return mapping.get(
        (level or "").lower(),
        30.0
    )